def _split_components(char):
    """Phân tích chữ thành bộ thủ."""
    char = normalize_kangxi(char)

    if char in MANUAL_DECOMPOSITIONS:
        parts = MANUAL_DECOMPOSITIONS[char]
        result = []
        for part in parts:
            info = get_radical_info(part)
            if info:
                result.append({
                    "zh": part,
                    "pinyin": info.get("pinyin", ""),
                    "strokes": info.get("strokes", ""),
                    "meaning": info.get("meaning", ""),
                    "position": _get_position(part),
                })
        if result:
            return result

    if HAS_CJKRADLIB and _RADICAL_FINDER:
        try:
            obj = _RADICAL_FINDER.search(char)
            compositions = getattr(obj, 'compositions', [])

            result = []
            for comp in compositions:
                if not comp:
                    continue
                if not ('\u4e00' <= comp[0] <= '\u9fff'):
                    continue

                info = get_radical_info(comp)
                if info:
                    result.append({
                        "zh": comp,
                        "pinyin": info.get("pinyin", ""),
                        "strokes": info.get("strokes", ""),
                        "meaning": info.get("meaning", ""),
                        "position": _get_position(comp),
                    })
                else:
                    result.append({
                        "zh": comp,
                        "pinyin": "",
                        "strokes": "",
                        "meaning": "",
                        "position": _get_position(comp),
                    })

            if result:
                return result
        except Exception as e:
            print(f"[WARN] cjkradlib.search('{char}') error: {e}")

    return []


def find_components(hanzi):
    if not hanzi:
        return []

    hanzi = normalize_kangxi(hanzi)

    components = []
    seen = set()

    for ch in hanzi:
        if not ('\u4e00' <= ch <= '\u9fff'):
            continue

        comps = _split_components(ch)
        for c in comps:
            key = c["zh"]
            if key in seen:
                continue
            seen.add(key)
            components.append(c)

    return components


def analyze_word(zh):
    if not zh:
        return {"chars": [], "components": [], "main_radical": None}

    zh = normalize_kangxi(zh)

    chars = [c for c in zh if '\u4e00' <= c <= '\u9fff']
    all_components = find_components(zh)

    main = None
    if chars:
        first_comps = _split_components(chars[0])
        if first_comps:
            sorted_comps = sorted(
                first_comps,
                key=lambda c: POSITION_PRIORITY.get(
                    c.get("position", "unknown"), 99
                )
            )
            main = sorted_comps[0]
        elif all_components:
            main = all_components[0]

    return {
        "chars": chars,
        "components": all_components,
        "main_radical": main,
    }


def get_radical_for_word(zh):
    result = analyze_word(zh)
    return result.get("main_radical")


def get_all_components_for_word(zh):
    result = analyze_word(zh)
    return result.get("components", [])
