def normalize_kangxi(text):
    if not text:
        return text
    result = []
    for ch in text:
        cp = ord(ch)
        if 0x2F00 <= cp <= 0x2FDF and cp in KANGXI_TO_CJK:
            result.append(chr(KANGXI_TO_CJK[cp]))
        else:
            result.append(ch)
    return ''.join(result)


